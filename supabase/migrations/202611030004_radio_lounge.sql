    execute format('revoke all on function public.%I(%s) from public,anon,authenticated',fn.proname,fn.args);
    if fn.proname<>'radio_nickname' then execute format('grant execute on function public.%I(%s) to authenticated',fn.proname,fn.args); end if;
    if fn.proname='discover_radio' then execute format('grant execute on function public.%I(%s) to anon',fn.proname,fn.args); end if;
  end loop;
end $$;
