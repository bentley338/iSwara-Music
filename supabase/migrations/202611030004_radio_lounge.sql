create table if not exists public.radio_channels (
  room_id uuid primary key references public.listening_rooms(id) on delete cascade,
  visibility text not null check(visibility in ('public','private')),
  description text not null default '' check(length(description)<=240),
  mood text not null default 'all' check(mood in ('all','chill','focus','pop','indie','night','energy')),
  created_at timestamptz not null default clock_timestamp()
);
create table if not exists public.radio_profiles (
  room_id uuid not null references public.radio_channels(room_id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  nickname text not null check(length(nickname) between 1 and 32),
  primary key(room_id,user_id)
);
create table if not exists public.radio_bans (
  room_id uuid not null references public.radio_channels(room_id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default clock_timestamp(),
  primary key(room_id,user_id)
);
create table if not exists public.radio_messages (
  id bigint generated by default as identity primary key,
  room_id uuid not null references public.radio_channels(room_id) on delete cascade,
  sender_id uuid not null references auth.users(id) on delete cascade,
  operation uuid not null, nickname text not null,
  kind text not null check(kind in ('comment','reaction')),
  body text not null check(length(body)<=280), removed boolean not null default false,
  created_at timestamptz not null default clock_timestamp(), unique(room_id,sender_id,operation)
);
create index if not exists radio_messages_room_order on public.radio_messages(room_id,id desc);
create table if not exists public.radio_receipts (
  room_id uuid not null references public.radio_channels(room_id) on delete cascade,
  sender_id uuid not null references auth.users(id) on delete cascade,
  operation uuid not null, message_id bigint not null, primary key(room_id,sender_id,operation)
);
create index if not exists radio_channels_discovery on public.radio_channels(visibility,created_at desc,room_id desc);
alter table public.radio_channels enable row level security;
alter table public.radio_profiles enable row level security;
alter table public.radio_bans enable row level security;
alter table public.radio_messages enable row level security;
alter table public.radio_receipts enable row level security;
revoke all on public.radio_channels,public.radio_profiles,public.radio_bans,public.radio_messages from public,anon,authenticated;
grant select on public.radio_channels,public.radio_profiles,public.radio_messages to authenticated;
grant all on public.radio_channels,public.radio_profiles,public.radio_bans,public.radio_messages to service_role;
revoke all on public.radio_receipts from public,anon,authenticated;
grant all on public.radio_receipts to service_role;
revoke all on sequence public.radio_messages_id_seq from public,anon,authenticated;
grant all on sequence public.radio_messages_id_seq to service_role;

create or replace function public.listening_member(p_room uuid) returns boolean language sql stable security definer set search_path='' as $$
  select public.account_active()
    and exists(select 1 from public.listening_members where room_id=p_room and user_id=auth.uid())
    and not exists(select 1 from public.radio_bans where room_id=p_room and user_id=auth.uid());
$$;
drop policy if exists radio_channel_members on public.radio_channels;
create policy radio_channel_members on public.radio_channels for select to authenticated using(public.listening_member(room_id));
drop policy if exists radio_profiles_members on public.radio_profiles;
create policy radio_profiles_members on public.radio_profiles for select to authenticated using(public.listening_member(room_id));
drop policy if exists radio_messages_members on public.radio_messages;
create policy radio_messages_members on public.radio_messages for select to authenticated using(public.listening_member(room_id));

create or replace function public.join_listening_room(p_code text) returns jsonb language plpgsql security definer set search_path='' as $$
declare uid uuid := public.listening_identity(); r public.listening_rooms;
begin
  if length(p_code)>40 then raise exception 'Kode room tidak valid.'; end if;
  select * into r from public.listening_rooms where code=regexp_replace(upper(p_code),'[^A-Z0-9]','','g') and closed_at is null and expires_at>now() for update;
  if r.id is null then raise exception 'Room tidak ditemukan atau sudah berakhir.'; end if;
  if exists(select 1 from public.radio_bans where room_id=r.id and user_id=uid) then raise exception 'Akses siaran ini dibatasi host.' using errcode='42501'; end if;
  if not exists(select 1 from public.listening_members where room_id=r.id and user_id=uid) then
    if (select count(*) from public.listening_members where room_id=r.id)>=32 then raise exception 'Room penuh; maksimal 32 anggota.'; end if;
    insert into public.listening_members(room_id,user_id) values(r.id,uid);
    update public.listening_rooms set revision=revision+1 where id=r.id;
  end if;
  return public.listening_state(r.id);
end $$;

create or replace function public.listening_state(p_room uuid) returns jsonb language plpgsql security definer set search_path='' as $$
declare r public.listening_rooms;
begin
  perform public.listening_identity();
  if not public.listening_member(p_room) then raise exception 'Kamu bukan anggota room ini.' using errcode='42501'; end if;
  select * into strict r from public.listening_rooms where id=p_room;
  return (to_jsonb(r)-'creation_op') || jsonb_build_object('server_ms',floor(extract(epoch from clock_timestamp())*1000)::bigint,
    'changed_ms',floor(extract(epoch from r.changed_at)*1000)::bigint,'host_seen_ms',floor(extract(epoch from r.host_seen_at)*1000)::bigint,
    'expires_ms',floor(extract(epoch from r.expires_at)*1000)::bigint,
    'closed',r.closed_at is not null or r.expires_at<=now(), 'radio',exists(select 1 from public.radio_channels where room_id=p_room),
    'members',(select count(*) from public.listening_members where room_id=p_room));
end $$;

create or replace function public.radio_nickname(p_name text) returns text language plpgsql immutable set search_path='' as $$
declare clean text := trim(regexp_replace(coalesce(p_name,''),'[[:cntrl:]]','','g'));
begin
  if length(clean) not between 1 and 32 then raise exception 'Nama tampilan harus 1-32 karakter.'; end if;
  return clean;
end $$;

create or replace function public.create_radio(p_title text,p_description text,p_visibility text,p_mood text,p_nickname text,p_operation uuid) returns jsonb language plpgsql security definer set search_path='' as $$
declare uid uuid := public.listening_identity(); data jsonb; rid uuid; nick text := public.radio_nickname(p_nickname);
begin
  if p_visibility not in ('public','private') or p_mood not in ('all','chill','focus','pop','indie','night','energy') or length(coalesce(p_description,''))>240 then raise exception 'Pilihan siaran tidak valid.'; end if;
  data := public.create_listening_room(p_title,p_operation); rid := (data->>'id')::uuid;
  insert into public.radio_channels(room_id,visibility,description,mood) values(rid,p_visibility,coalesce(p_description,''),p_mood) on conflict do nothing;
  insert into public.radio_profiles(room_id,user_id,nickname) values(rid,uid,nick) on conflict do nothing;
  return public.listening_state(rid);
end $$;

create or replace function public.join_radio(p_code text,p_nickname text) returns jsonb language plpgsql security definer set search_path='' as $$
declare uid uuid := public.listening_identity(); data jsonb; rid uuid; nick text := public.radio_nickname(p_nickname);
begin
  if not exists(select 1 from public.listening_rooms r join public.radio_channels c on c.room_id=r.id where r.code=regexp_replace(upper(p_code),'[^A-Z0-9]','','g')) then raise exception 'Siaran tidak ditemukan.'; end if;
  data := public.join_listening_room(p_code); rid := (data->>'id')::uuid;
  insert into public.radio_profiles(room_id,user_id,nickname) values(rid,uid,nick) on conflict(room_id,user_id) do update set nickname=excluded.nickname;
  return data;
end $$;

create or replace function public.discover_radio(p_query text default '',p_mood text default 'all',p_before timestamptz default null,p_before_id uuid default null) returns jsonb language plpgsql stable security definer set search_path='' as $$
declare items jsonb; last_item jsonb;
begin
  if length(coalesce(p_query,''))>80 or p_mood not in ('all','chill','focus','pop','indie','night','energy') or (p_before is null)<>(p_before_id is null) then raise exception 'Pencarian siaran tidak valid.'; end if;
  select coalesce(jsonb_agg(row_data order by created_at desc,room_id desc),'[]') into items from (
    select c.created_at,c.room_id,jsonb_build_object('id',r.id,'code',r.code,'title',r.title,'description',c.description,'mood',c.mood,
      'host_name',coalesce(p.nickname,'Host iSwara'),'playing',r.playing,'track',r.queue->r.current_index,'created_at',c.created_at,
      'members',(select count(*) from public.listening_members m where m.room_id=r.id)) row_data
    from public.radio_channels c join public.listening_rooms r on r.id=c.room_id
    left join public.radio_profiles p on p.room_id=r.id and p.user_id=r.host_id
    where c.visibility='public' and r.closed_at is null and r.expires_at>now() and r.host_seen_at>now()-interval '90 seconds'
      and exists(select 1 from auth.users u where u.id=r.host_id and u.email_confirmed_at is not null and (u.banned_until is null or u.banned_until<=now()))
      and (p_mood='all' or c.mood=p_mood)
      and (coalesce(p_query,'')='' or position(lower(p_query) in lower(r.title||' '||c.description||' '||coalesce(p.nickname,'')))>0)
      and (p_before is null or (c.created_at,c.room_id)<(p_before,p_before_id))
    order by c.created_at desc,c.room_id desc limit 20
  ) page;
  last_item := items->(jsonb_array_length(items)-1);
  return jsonb_build_object('items',items,'next_created',case when jsonb_array_length(items)=20 then last_item->>'created_at' else null end,
    'next_id',case when jsonb_array_length(items)=20 then last_item->>'id' else null end);
end $$;

create or replace function public.radio_state(p_room uuid,p_before bigint default null) returns jsonb language plpgsql security definer set search_path='' as $$
declare uid uuid := public.listening_identity(); r public.listening_rooms; c public.radio_channels; messages jsonb;
begin
  if not public.listening_member(p_room) then raise exception 'Bergabung dahulu untuk membuka lounge.' using errcode='42501'; end if;
  select * into strict r from public.listening_rooms where id=p_room;
  select * into strict c from public.radio_channels where room_id=p_room;
  select coalesce(jsonb_agg(to_jsonb(message) order by id),'[]') into messages from
    (select id,sender_id,nickname,kind,body,removed,created_at from public.radio_messages where room_id=p_room and (p_before is null or id<p_before) order by id desc limit 50) message;
  return jsonb_build_object('title',r.title,'description',c.description,'visibility',c.visibility,'mood',c.mood,
    'host_name',(select nickname from public.radio_profiles where room_id=p_room and user_id=r.host_id),
    'nickname',(select nickname from public.radio_profiles where room_id=p_room and user_id=uid),
    'messages',messages,'can_moderate',r.host_id=uid or public.is_admin());
end $$;

create or replace function public.radio_post(p_room uuid,p_kind text,p_body text,p_operation uuid) returns bigint language plpgsql security definer set search_path='' as $$
declare uid uuid := public.listening_identity(); mid bigint; nick text; clean text := trim(regexp_replace(coalesce(p_body,''),'[[:cntrl:]]','','g'));
begin
  perform pg_advisory_xact_lock(hashtextextended(p_room::text||uid::text,1));
  if not public.listening_member(p_room) then raise exception 'Bergabung dahulu untuk mengirim pesan.' using errcode='42501'; end if;
  if not exists(select 1 from public.listening_rooms where id=p_room and closed_at is null and expires_at>now()) then raise exception 'Siaran sudah berakhir.'; end if;
  select message_id into mid from public.radio_receipts where room_id=p_room and sender_id=uid and operation=p_operation;
  if mid is not null then return mid; end if;
  if exists(select 1 from public.radio_messages where room_id=p_room and sender_id=uid and created_at>clock_timestamp()-interval '2 seconds') then raise exception 'Tunggu sebentar sebelum mengirim lagi.'; end if;
  if p_kind not in ('comment','reaction') or length(clean) not between 1 and 280 or (p_kind='reaction' and clean not in ('heart','fire','clap','music','wow')) then raise exception 'Pesan atau reaksi tidak valid.'; end if;
  select nickname into nick from public.radio_profiles where room_id=p_room and user_id=uid;
  insert into public.radio_messages(room_id,sender_id,operation,nickname,kind,body) values(p_room,uid,p_operation,coalesce(nick,'Pendengar iSwara'),p_kind,clean) returning id into mid;
  insert into public.radio_receipts(room_id,sender_id,operation,message_id) values(p_room,uid,p_operation,mid);
  delete from public.radio_messages where room_id=p_room and id not in (select id from public.radio_messages where room_id=p_room order by id desc limit 500);
  return mid;
end $$;

create or replace function public.radio_update(p_room uuid,p_title text,p_description text,p_visibility text,p_mood text) returns void language plpgsql security definer set search_path='' as $$
declare uid uuid := public.listening_identity();
begin
  if not exists(select 1 from public.listening_rooms where id=p_room and host_id=uid and closed_at is null and expires_at>now()) then raise exception 'Hanya host yang bisa mengubah siaran.' using errcode='42501'; end if;
  if length(trim(p_title)) not between 1 and 80 or length(coalesce(p_description,''))>240 or p_visibility not in ('public','private') or p_mood not in ('all','chill','focus','pop','indie','night','energy') then raise exception 'Pengaturan siaran tidak valid.'; end if;
  update public.radio_channels set visibility=p_visibility,description=coalesce(p_description,''),mood=p_mood where room_id=p_room;
  if not found then raise exception 'Siaran tidak ditemukan.'; end if;
  update public.listening_rooms set title=trim(p_title),revision=revision+1 where id=p_room;
end $$;

create or replace function public.radio_moderate(p_room uuid,p_action text,p_message bigint default null,p_target uuid default null) returns void language plpgsql security definer set search_path='' as $$
declare uid uuid := public.listening_identity(); host uuid; moderator boolean;
begin
  select host_id into host from public.listening_rooms where id=p_room;
  moderator := host=uid or public.is_admin();
  if p_action='remove' then
    if not moderator and not exists(select 1 from public.radio_messages where room_id=p_room and id=p_message and sender_id=uid) then raise exception 'Tidak berhak menghapus pesan ini.' using errcode='42501'; end if;
    update public.radio_messages set body='',removed=true where room_id=p_room and id=p_message;
  elsif p_action='ban' then
    if not moderator or p_target is null or p_target=host or p_target=uid then raise exception 'Tidak berhak membatasi anggota ini.' using errcode='42501'; end if;
    insert into public.radio_bans(room_id,user_id) values(p_room,p_target) on conflict do nothing;
    delete from public.listening_members where room_id=p_room and user_id=p_target;
    update public.listening_rooms set revision=revision+1 where id=p_room;
  else raise exception 'Tindakan moderasi tidak valid.';
  end if;
end $$;

do $$ declare fn record;
begin
  for fn in select p.proname,pg_get_function_identity_arguments(p.oid) args from pg_proc p join pg_namespace n on n.oid=p.pronamespace
